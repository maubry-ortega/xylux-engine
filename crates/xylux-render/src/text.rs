use crate::vertex::Vertex;
use glam::Vec3;

/// Basic 5x7 bitmap font data (A-Z, 0-9, basic symbols)
/// Represented as bytes where bits 0-4 are pixels.
/// Row 0 is top.
fn get_char_bitmap(c: char) -> [u8; 7] {
    match c.to_ascii_uppercase() {
        'A' => [0x04, 0x0A, 0x11, 0x11, 0x1F, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        'D' => [0x1C, 0x09, 0x11, 0x11, 0x11, 0x09, 0x1C],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x13, 0x11, 0x11, 0x0E],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x11, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x09, 0x16],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0E, 0x11, 0x10, 0x0E, 0x01, 0x11, 0x0E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F],
        '3' => [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        '6' => [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
        '-' => [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C],
        ':' => [0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00],
        ' ' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        _ => [0x1F, 0x15, 0x1F, 0x15, 0x1F, 0x15, 0x1F], // Block for unknown
    }
}

pub fn generate_text_mesh(text: &str, start_pos: Vec3, scale: f32, color: Vec3) -> Vec<Vertex> {
    let mut vertices = Vec::new();
    let mut cursor_x = start_pos.x;
    let cursor_y = start_pos.y; // Top-left origin for char
    
    // Pixel size
    let px = scale * 0.2; // Width of a "pixel"
    let py = scale * 0.2; // Height of a "pixel"
    
    let char_spacing = px * 1.5;

    for c in text.chars() {
        let bitmap = get_char_bitmap(c);
        
        // Draw 5x7 grid
        for row in 0..7 {
            let row_byte = bitmap[row];
            for col in 0..5 {
                // Check bit (bit 4 is left-most, bit 0 is right-most in our hex above?
                // Example 'A': 0x04 = 00100. Middle pixel.
                // Actually my hexes seem to assume bit 0 is right.
                // 0x04 = 00100 -> col 2 is set.
                // Let's iterate col 0..5. Bit index = 4 - col.
                let bit_idx = 4 - col;
                if (row_byte >> bit_idx) & 1 == 1 {
                    let pixel_x = cursor_x + (col as f32 * px);
                    let pixel_y = cursor_y + (row as f32 * py); // Y goes down in Vulkan (increase Y)
                    
                    // Quad
                    // v1 (Top-Left) at pixel_y
                    // v3 (Bottom-Right) at pixel_y + py
                    
                    let v1 = Vertex { pos: Vec3::new(pixel_x, pixel_y, start_pos.z), color, normal: Vec3::Z };
                    let v2 = Vertex { pos: Vec3::new(pixel_x + px, pixel_y, start_pos.z), color, normal: Vec3::Z };
                    let v3 = Vertex { pos: Vec3::new(pixel_x + px, pixel_y + py, start_pos.z), color, normal: Vec3::Z };
                    let v4 = Vertex { pos: Vec3::new(pixel_x, pixel_y + py, start_pos.z), color, normal: Vec3::Z };
                    
                    vertices.push(v1); vertices.push(v2); vertices.push(v3);
                    vertices.push(v1); vertices.push(v3); vertices.push(v4);
                }
            }
        }
        
        cursor_x += (5.0 * px) + char_spacing;
    }
    
    vertices
}
